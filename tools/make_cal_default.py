#!/usr/bin/env python3
"""Generate drivers/cal_default.c / cal_default.h: the default RF calibration block for a radio.

The default calibration is what a radio's firmware writes to its calibration NAND block when it formats a blank data
area. This script gets it by running a firmware image you supply in the emulator on a NAND without a calibration
block and without the data-area marker, and copying the calibration block the firmware writes. Alternatively it
takes the block from a NAND pages file you already have (--nand, e.g. a backup of your own radio).

  python3 tools/make_cal_default.py --radio d890 --image FIRMWARE.bin          # writes drivers/cal_default.[ch]
  python3 tools/make_cal_default.py --radio d168 --image fw.bin --out ../../D168UV/cfw/drivers
  python3 tools/make_cal_default.py --radio d890 --nand backup.pages

Layout of the output (as drivers/dac.c reads the NAND block): cal_default[i] = byte i of the calibration block,
i < CAL_DEFAULT_LEN; 0xFF = not set. The block's valid marker is not included.
"""
import argparse
import os
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.realpath(__file__))
CFW = os.path.dirname(HERE)

RADIOS = {
    # page size, cal block, block size, data-area marker page, pages to drop besides cal + marker, emu tree, boot s
    "d890": dict(page=0x1000, cal=0x04F00000, block=0x40000, marker=0x04EC0000, drop=[(0x04F40000, 0x40000)],
                 emu=os.path.join(os.path.dirname(CFW), "emu"), seconds=20),
    "d168": dict(page=0x800, cal=0x02F60000, block=0x20000, marker=0x02FE0000,
                 drop=[(0x02F80000, 0x20000), (0x02500000, 0x20000)],
                 emu=os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(CFW))), "D168UV", "emu"), seconds=15),
}


def read_pages(path, page):
    d = open(path, "rb").read()
    return {struct.unpack_from("<I", d, o)[0]: d[o + 4:o + 4 + page] for o in range(0, len(d), 4 + page)}


def write_pages(path, pages, page):
    with open(path, "wb") as f:
        for a in sorted(pages):
            f.write(struct.pack("<I", a) + bytes(pages[a]))


def run_firmware(r, image, work):
    emu = r["emu"]
    base = os.path.join(work, "base.pages")
    subprocess.check_call([sys.executable, os.path.join(emu, "make_nand.py"), "--out", base])
    pages = read_pages(base, r["page"])
    drop = [(r["cal"], r["block"]), (r["marker"], r["page"])] + r["drop"]
    pages = {a: p for a, p in pages.items() if not any(s <= a < s + n for s, n in drop)}
    blank = os.path.join(work, "blank.pages")
    write_pages(blank, pages, r["page"])
    after = os.path.join(work, "after.pages")
    cmd = [sys.executable, os.path.join(emu, "run.py"), "--image", os.path.abspath(image), "--nand", blank,
           "--seconds", str(r["seconds"]), "--name", "cal_default_gen", "--then", "0|nand SaveOverlay @%s" % after]
    subprocess.run(cmd, cwd=emu, check=False)
    if not os.path.exists(after):
        sys.exit("emulator run produced no NAND dump (see %s/out/cal_default_gen)" % emu)
    return after


def extract(r, nand):
    pages = read_pages(nand, r["page"])
    blk = bytearray(b"\xff" * r["block"])
    for a, p in pages.items():
        if r["cal"] <= a < r["cal"] + r["block"]:
            blk[a - r["cal"]:a - r["cal"] + len(p)] = p
    if blk[-4:] != b"\x55\x55\xaa\xaa":
        sys.exit("no valid calibration block at 0x%08X in %s" % (r["cal"], nand))
    body = blk[:r["block"] - r["page"]]                  # last page holds the block markers
    n = len(body.rstrip(b"\xff"))
    if n == 0:
        sys.exit("calibration block at 0x%08X is empty" % r["cal"])
    return bytes(body[:(n + 15) & ~15])


def emit(data, out):
    os.makedirs(out, exist_ok=True)
    h = ("/* Default RF calibration block (generated by tools/make_cal_default.py). */\n"
         "#ifndef CAL_DEFAULT_H\n#define CAL_DEFAULT_H\n#include <stdint.h>\n\n"
         "#define CAL_DEFAULT_LEN 0x%04Xu\n"
         "/* byte i of the calibration NAND block, i < CAL_DEFAULT_LEN (0xFF = not set) */\n"
         "extern const uint8_t cal_default[CAL_DEFAULT_LEN];\n\n#endif\n" % len(data))
    rows = ["    " + " ".join("0x%02X," % b for b in data[i:i + 16]) + "   /* +0x%04X */" % i
            for i in range(0, len(data), 16)]
    c = ("/* Default RF calibration block (generated by tools/make_cal_default.py). */\n"
         "#include \"cal_default.h\"\n\n"
         "const uint8_t cal_default[CAL_DEFAULT_LEN] = {\n" + "\n".join(rows) + "\n};\n")
    open(os.path.join(out, "cal_default.h"), "w").write(h)
    open(os.path.join(out, "cal_default.c"), "w").write(c)
    print("%s: cal_default.[ch], %d bytes" % (out, len(data)))


def main():
    ap = argparse.ArgumentParser(description="default RF calibration -> drivers/cal_default.[ch]")
    ap.add_argument("--radio", choices=sorted(RADIOS), required=True)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--image", help="firmware image to run in the emulator (as emu/run.py --image)")
    g.add_argument("--nand", help="NAND pages file that already holds a valid calibration block")
    ap.add_argument("--emu", help="emulator folder (default: the radio's emu tree)")
    ap.add_argument("--out", default=os.path.join(CFW, "drivers"), help="output folder (default cfw/drivers)")
    a = ap.parse_args()
    r = dict(RADIOS[a.radio])
    if a.emu:
        r["emu"] = os.path.abspath(a.emu)
    with tempfile.TemporaryDirectory() as work:
        nand = a.nand or run_firmware(r, a.image, work)
        emit(extract(r, nand), a.out)


if __name__ == "__main__":
    main()
