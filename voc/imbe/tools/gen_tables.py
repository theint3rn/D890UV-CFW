#!/usr/bin/env python3
"""Generate imbe_tables.c (compact IMBE 7200x4400 dequantisation tables) from
mbelib's imbe7200x4400_const.h (ISC licence, notice reproduced in the output).
Usage: gen_tables.py path/to/imbe7200x4400_const.h > imbe_tables.c"""
import re, sys

src = open(sys.argv[1]).read()
notice = src[src.index('/*'):src.index('*/') + 2]
body = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
body = re.sub(r'//[^\n]*', '', body)

def arr(name):
    m = re.search(r'\b' + name + r'\s*(\[[^=]*)=\s*\{(.*?)\};', body, re.S)
    nums = re.findall(r'-?\d+(?:\.\d*)?(?:[eE][-+]?\d+)?', m.group(2))
    return [float(x) for x in nums]

qs, sd, b2 = arr('quantstep'), arr('standdev'), arr('B2')
ba, hoba, bo, ji = arr('ba'), arr('hoba'), arr('bo'), arr('ImbeJi')
assert len(b2) == 64 and len(ba) == 48 * 5 * 2 and len(hoba) == 48 * 50
assert len(bo) == 48 * 79 * 2 and len(ji) == 48 * 6 and len(sd) == 9 and len(qs) >= 10

def rows(vals, per, fmt, nest=False):
    out = []
    for i in range(0, len(vals), per):
        t = ', '.join(fmt % v for v in vals[i:i + per])
        out.append('    ' + ('{' + t + '},' if nest else t + ','))
    return '\n'.join(out)

o = []
o.append('/* GENERATED by tools/gen_tables.py from mbelib imbe7200x4400_const.h - do not edit.\n'
         ' * IMBE 7200x4400 (P25 Phase 1) dequantisation tables, repacked into compact types.\n'
         ' * Original copyright and licence (ISC): */')
o.append(notice)
o.append('#include "imbe_tables.h"\n')
o.append('const float imbe_quantstep[10] = {\n' + rows(qs[:10], 10, '%.6gf') + '\n};\n')
o.append('const float imbe_standdev[9] = {\n' + rows(sd, 9, '%.6gf') + '\n};\n')
o.append('const float imbe_b2[64] = {\n' + rows(b2, 8, '%.6ff') + '\n};\n')
o.append('/* [L-9][G2..G6]: bits, step */')
o.append('const uint8_t imbe_ba_bits[48][5] = {\n' + rows([int(ba[2 * i]) for i in range(240)], 5, '%d', True) + '\n};\n')
o.append('const float imbe_ba_step[48][5] = {\n' + rows([ba[2 * i + 1] for i in range(240)], 5, '%.6ff', True) + '\n};\n')
o.append('/* [L-9][b8..]: bits of the higher-order DCT coefficients */')
o.append('const uint8_t imbe_hoba[48][50] = {\n' + rows([int(v) for v in hoba], 50, '%d', True) + '\n};\n')
o.append('/* [L-9][i]: info bit 6+i of the 88-bit frame -> parameter b_m (m) and its bit (b) */')
o.append('const uint8_t imbe_bo_m[48][79] = {\n' + rows([int(bo[2 * i]) for i in range(48 * 79)], 79, '%d', True) + '\n};\n')
o.append('const uint8_t imbe_bo_b[48][79] = {\n' + rows([int(bo[2 * i + 1]) for i in range(48 * 79)], 79, '%d', True) + '\n};\n')
o.append('/* [L-9][block]: residual block lengths J_i */')
o.append('const uint8_t imbe_ji[48][6] = {\n' + rows([int(v) for v in ji], 6, '%d', True) + '\n};')
print('\n'.join(o))
